// Writes src/version.ts from package.json (runs on `npm version` and before build).
import { readFileSync, writeFileSync } from 'node:fs'
const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'))
const file = new URL('../src/version.ts', import.meta.url)
const body = `// Generated by scripts/sync-version.mjs from package.json — do not edit.\nexport const ACP_CLIENT_VERSION = '${version}'\n`
let cur = ''
try { cur = readFileSync(file, 'utf8') } catch {}
if (cur !== body) writeFileSync(file, body)
